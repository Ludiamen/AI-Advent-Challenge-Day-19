        "| третий сохраняет результат | 1.5 (итог — путь файла .md), 2.1 (файл прочитан с диска) |",
        "| автоматическое выполнение цепочки | 1.3, 1.5 (один ключ — вся цепочка), 3.1 (модель одним вызовом), 1.11 (по расписанию) |",
