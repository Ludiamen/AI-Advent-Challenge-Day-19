@dataclass
class Шаг:
    """Одна проверка: что запускаем и что должно быть в выводе."""

    номер: str
    название: str
    ключи: list[str]
    ожидания: list[tuple[str, Callable[[str], bool]]] = field(default_factory=list)
    код_возврата: int | None = 0
    ввод: str = ""
    программа: str = "cli.py"
    # Команды cli.py получают свой каталог памяти и модель; доказательный
    # скрипт — нет, у него свои ключи.
    общие_ключи: bool = True
    нужна_модель: bool = False
    # Процесс, который должен работать во время шага (свой сервер по HTTP).
    фон: list[str] | None = None
    фон_порт: int = 0


@dataclass
class Итог:
    шаг: Шаг
    команда: str
    вывод: str
    код: int
    секунд: float
    сошлось: list[tuple[str, bool]] = field(default_factory=list)

    @property
    def удача(self) -> bool:
        return all(ок for _, ок in self.сошлось)


def есть(подстрока: str) -> Callable[[str], bool]:
    return lambda текст: подстрока.lower() in текст.lower()


def по_выражению(выражение: str) -> Callable[[str], bool]:
    сжатое = re.compile(выражение, re.IGNORECASE | re.MULTILINE)
    return lambda текст: bool(сжатое.search(текст))


def нет(подстрока: str) -> Callable[[str], bool]:
    return lambda текст: подстрока.lower() not in текст.lower()


def свободный_порт() -> int:
    with socket.socket() as с:
        с.bind(("127.0.0.1", 0))
        return с.getsockname()[1]


def ждать_порт(порт: int, секунд: float = 30) -> bool:
    предел = time.monotonic() + секунд
    while time.monotonic() < предел:
        try:
            socket.create_connection(("127.0.0.1", порт), timeout=0.5).close()
            return True
        except OSError:
            time.sleep(0.2)
    return False


def запустить(шаг: Шаг, модель: str) -> Итог:
    ключи = [sys.executable, шаг.программа]
    if шаг.общие_ключи:
        ключи += ["--память-в", ПАМЯТЬ_ОТН]
        if модель and шаг.нужна_модель:
            ключи += ["--модель", модель]
    ключи += шаг.ключи

    фон = None
    if шаг.фон:
        фон = subprocess.Popen(шаг.фон, cwd=КОРЕНЬ, stdin=subprocess.DEVNULL,
                               stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        # Порт ждём, только если он есть: фоном бывает и работник планировщика,
        # который ничего не слушает.
        if шаг.фон_порт:
            ждать_порт(шаг.фон_порт)
    начало = time.time()
    # stdin закрыт: команда, которая по ошибке уходит в диалог, в терминале
    # виснет на «Вы:». С закрытым вводом она завершится, а проверка ниже поймает
    # саму ошибку. Таймаут — вторая страховка.
    try:
        готово = subprocess.run(
            ключи, capture_output=True, text=True, cwd=КОРЕНЬ,
            input=шаг.ввод if шаг.ввод else None,
            stdin=None if шаг.ввод else subprocess.DEVNULL,
            timeout=ПРЕДЕЛ_СЕКУНД)
        вывод = (готово.stdout or "") + (готово.stderr or "")
        код = готово.returncode
    except subprocess.TimeoutExpired as истекло:
        вывод = ((истекло.stdout or b"").decode("utf-8", "replace")
                 + (истекло.stderr or b"").decode("utf-8", "replace")
                 + f"\n[команда не завершилась за {ПРЕДЕЛ_СЕКУНД} с]")
        код = -1
    finally:
        if фон is not None:
            фон.terminate()
            try:
                фон.wait(timeout=10)
            except subprocess.TimeoutExpired:
                фон.kill()
    итог = Итог(шаг=шаг, команда=" ".join(ключи[1:]), вывод=вывод,
                код=код, секунд=time.time() - начало)
    if not шаг.ввод:
        итог.сошлось.append(
            ("команда завершилась сама, не открыв диалог", "Вы:" not in вывод))
    for описание, проверка in шаг.ожидания:
        итог.сошлось.append((описание, bool(проверка(вывод))))
    if шаг.код_возврата is not None:
        итог.сошлось.append((f"код возврата {шаг.код_возврата}", код == шаг.код_возврата))
    return итог


